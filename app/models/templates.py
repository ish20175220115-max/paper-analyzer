def get_dimension_by_key(key: str) -> dict | None:
    """根据 key 获取维度定义"""
    for d in ANALYSIS_DIMENSIONS:
        if d["key"] == key:
            return d
    return None


def get_dimension_labels(keys: list[str]) -> list[str]:
    """将 key 列表转为中文标签列表"""
    label_map = {d["key"]: d["label"] for d in ANALYSIS_DIMENSIONS}
    return [label_map.get(k, k) for k in keys]


def get_full_prompt(dimension: dict) -> str:
    """获取完整的 prompt 描述（含 system_hint，用于注入后端）"""
    desc = dimension.get("description", "")
    hint = dimension.get("system_hint", "")
    if hint:
        return f"{desc}\n\n{hint}"
    return desc
